// One-time migration helper: converts each legacy standalone HTML page into
// a React page component under app/src/pages/<Slug>/, without altering the
// page's actual markup, CSS, or JS. Every extracted file's contents are a
// verbatim substring of the original HTML file.
//
// Usage: node scripts/migrate-pages-to-react.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const APP_PAGES_DIR = join(ROOT, 'app', 'src', 'pages');

// [sourceHtmlPath relative to repo root, output slug, route path]
const PAGES = [
  ['index.html', 'Questionnaire', '/'],
  ['luxury-apartments-premium.html', 'LuxuryApartmentsPremium', '/luxury-apartments-premium'],
  ['modern-apartments-premium.html', 'ModernApartmentsPremium', '/modern-apartments-premium'],
  ['real-estate-list.html', 'RealEstateList', '/real-estate-list'],
  ['after-payment-results/index.html', 'AfterPaymentResults', '/after-payment-results'],
  ['rentready-review-checkout.html', 'RentreadyReviewCheckout', '/rentready-review-checkout'],
  ['credit-action-package.html', 'CreditActionPackage', '/credit-action-package'],
  ['game-plan.html', 'GamePlan', '/game-plan'],
  ['membership.html', 'Membership', '/membership'],
  ['thank-you.html', 'ThankYou', '/thank-you'],
  ['results-processing.html', 'ResultsProcessing', '/results-processing'],
];

function extractAll(regex, html) {
  const out = [];
  let m;
  const re = new RegExp(regex);
  while ((m = re.exec(html))) {
    out.push(m);
    if (!re.global) break;
  }
  return out;
}

function migratePage(sourceRelPath, slug, routePath) {
  const sourcePath = join(ROOT, sourceRelPath);
  const html = readFileSync(sourcePath, 'utf8');

  const titleMatch = html.match(/<title>([\s\S]*?)<\/title>/i);
  const title = titleMatch ? titleMatch[1].trim() : slug;

  // Head extras: font preconnect/stylesheet <link> tags only. Everything
  // else in <head> (charset/viewport/style) is either irrelevant once
  // bundled by Vite or handled separately below.
  const headMatch = html.match(/<head[^>]*>([\s\S]*?)<\/head>/i);
  const headHtml = headMatch ? headMatch[1] : '';
  const linkTags = extractAll(/<link\b[^>]*>/gi, headHtml).map((m) => m[0]);
  const fontLinkTags = linkTags.filter((tag) => /fonts\.googleapis|fonts\.gstatic/i.test(tag));
  const headExtras = fontLinkTags.join('\n');

  // <style> block (the pages in this project each have exactly one).
  const styleMatch = html.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
  const styles = styleMatch ? styleMatch[1] : '';

  // Body content, with every <script> tag (inline or external) stripped
  // out, plus each inline script's contents captured separately in
  // document order. External <script src="..."> tags found in the body are
  // reported so they can be checked against the globally-loaded scripts in
  // app/index.html rather than being silently dropped.
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  let bodyHtml = bodyMatch ? bodyMatch[1] : '';

  const scripts = [];
  const externalSrcs = [];
  bodyHtml = bodyHtml.replace(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi, (whole, attrs, content) => {
    const srcMatch = attrs.match(/src=["']([^"']+)["']/i);
    if (srcMatch) {
      externalSrcs.push(srcMatch[1]);
      return '';
    }
    if (content.trim()) scripts.push(content);
    return '';
  });

  const outDir = join(APP_PAGES_DIR, slug);
  mkdirSync(outDir, { recursive: true });

  writeFileSync(join(outDir, 'page.html'), bodyHtml, 'utf8');
  writeFileSync(join(outDir, 'page.css'), styles, 'utf8');
  writeFileSync(join(outDir, 'head-extras.html'), headExtras, 'utf8');
  scripts.forEach((content, i) => {
    writeFileSync(join(outDir, `script-${i}.js`), content, 'utf8');
  });

  const scriptImports = scripts
    .map((_, i) => `import script${i} from './script-${i}.js?raw';`)
    .join('\n');
  const scriptArray = scripts.map((_, i) => `script${i}`).join(', ');

  const jsx = `// AUTO-GENERATED by scripts/migrate-pages-to-react.mjs from ${sourceRelPath}.
// The imported .html/.css/.js files are verbatim extracts of the original
// page. Do not hand-edit the extracted files without re-running the
// migration script, or the two will drift.
import bodyHtml from './page.html?raw';
import styles from './page.css?raw';
import headExtras from './head-extras.html?raw';
${scriptImports}
import { useLegacyPage } from '../../legacy/useLegacyPage';

export default function ${slug}() {
  const containerRef = useLegacyPage({
    title: ${JSON.stringify(title)},
    headExtras,
    styles,
    bodyHtml,
    scripts: [${scriptArray}],
  });
  return <div ref={containerRef} />;
}
`;
  writeFileSync(join(outDir, 'index.jsx'), jsx, 'utf8');

  return { slug, routePath, title, scriptCount: scripts.length, externalSrcs };
}

const results = PAGES.map(([src, slug, route]) => migratePage(src, slug, route));

writeFileSync(
  join(APP_PAGES_DIR, 'manifest.json'),
  JSON.stringify(results, null, 2),
  'utf8'
);

console.log('Migrated pages:');
for (const r of results) {
  console.log(`  ${r.routePath.padEnd(28)} -> pages/${r.slug} (${r.scriptCount} script block(s))`);
  if (r.externalSrcs.length) {
    console.log(`      external <script src> found: ${r.externalSrcs.join(', ')}`);
  }
}
